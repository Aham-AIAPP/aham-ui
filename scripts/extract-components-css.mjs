import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
const dir=new URL('../design-system/',import.meta.url);
const files=readdirSync(new URL('preview/',dir)).filter(f=>/^component-.*\.html$/.test(f)).sort();
const out=['/* Generated by scripts/extract-components-css.mjs from preview markers. */'];
for(const f of files){
 const source=readFileSync(new URL(`preview/${f}`,dir),'utf8');
 const matches=[...source.matchAll(/\/\* @component-css-start \*\/([\s\S]*?)\/\* @component-css-end \*\//g)];
 if(matches.length!==1)throw new Error(`Expected one CSS block: ${f}`);
 out.push(`/* ${f} */\n${matches[0][1].trim()}`);
}
const css=out.join('\n\n')+'\n',target=new URL('components.css',dir);
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==css)throw new Error('Component CSS drift');}
else writeFileSync(target,css);
console.log(`Extracted ${files.length} component previews`);
